"""Builder C's room drawing helper: draws zone rooms as ASCII grids with a few primitives and
writes game/data/rooms/zone-NN.js (plain data, the engine's room format: design/ENGINE_NOTES.md).

    from zonegen_c import Zone, Room
    z = Zone('z07-study', 7, 'Study', palette=[...], start={'room': 'stu-door'}, extra={...})
    r = z.room('stu-door', 'The Study Door', 18, 4, 1, 2)       # cell x, y; size in screens
    r.fill(0, 16, 32, 2, '#'); r.clear(0, 8, 1, 4); r.put(3, 15, 'S')
    r.ent('sign', x=2, y=15, w=6, text='...'); r.deco('book-spine', 5, 15, 2.5)
    z.write('game/data/rooms/zone-07.js')

Every room starts as open air inside a solid 1-tile border; open the exits with clear().
"""
import json, os, sys

W, H = 32, 18


class Room:
    def __init__(self, rid, name, cx, cy, sw, sh, **o):
        self.id, self.name, self.cx, self.cy, self.sw, self.sh = rid, name, cx, cy, sw, sh
        self.w, self.h = sw * W, sh * H
        self.g = [['.'] * self.w for _ in range(self.h)]
        for x in range(self.w):
            self.g[0][x] = '#'; self.g[self.h - 1][x] = '#'
        for y in range(self.h):
            self.g[y][0] = '#'; self.g[y][self.w - 1] = '#'
        self.o = o
        self.ents, self.decor, self.paint = [], [], []

    # ---- tiles ----
    def fill(self, x, y, w, h, ch='#'):
        for yy in range(y, y + h):
            for xx in range(x, x + w):
                if 0 <= xx < self.w and 0 <= yy < self.h:
                    self.g[yy][xx] = ch
        return self

    def clear(self, x, y, w=1, h=1):
        return self.fill(x, y, w, h, '.')

    def put(self, x, y, ch):
        self.g[y][x] = ch
        return self

    def text(self, x, y, s):
        for i, ch in enumerate(s):
            if ch != ' ':
                self.g[y][x + i] = ch
        return self

    def plat(self, x, y, w, ch='='):
        return self.fill(x, y, w, 1, ch)

    def floor(self, y, ch='#', x0=0, x1=None):
        x1 = self.w if x1 is None else x1
        return self.fill(x0, y, x1 - x0, self.h - y, ch)

    def tile(self, x, y):
        return self.g[y][x]

    # ---- entities and decor ----
    def ent(self, type, **kw):
        e = {'type': type}; e.update(kw); self.ents.append(e)
        return self

    def deco(self, prop, x, y, h, **kw):
        d = {'prop': prop, 'x': x, 'y': y, 'h': h}; d.update(kw); self.decor.append(d)
        return self

    def paint_box(self, kind, x, y, w, h):
        self.paint.append({'kind': kind, 'x': x, 'y': y, 'w': w, 'h': h})
        return self

    def rows(self):
        return [''.join(r) for r in self.g]

    def dump(self):
        print(f'--- {self.id} ({self.w}x{self.h})')
        print('     ' + ''.join(str(i // 10) if i % 10 == 0 else ' ' for i in range(self.w)))
        print('     ' + ''.join(str(i % 10) for i in range(self.w)))
        for y, r in enumerate(self.rows()):
            print(f'{y:3d}  {r}')

    def to_js(self):
        out = ['    {']
        out.append(f'      id: {json.dumps(self.id)}, name: {json.dumps(self.name)},')
        out.append(f'      x: {self.cx}, y: {self.cy},')
        for k, v in self.o.items():
            out.append(f'      {k}: {json.dumps(v)},')
        if self.decor:
            out.append('      decor: [')
            for d in self.decor:
                out.append(f'        {json.dumps(d)},')
            out.append('      ],')
        if self.paint:
            out.append(f'      paint: {json.dumps(self.paint)},')
        out.append('      grid: [')
        for r in self.rows():
            out.append(f"        '{r}',")
        out.append('      ],')
        out.append('      entities: [')
        for e in self.ents:
            out.append(f'        {json.dumps(e)},')
        out.append('      ],')
        out.append('    },')
        return '\n'.join(out)


class Zone:
    def __init__(self, zid, n, name, header='', **fields):
        self.id, self.n, self.name, self.header, self.fields = zid, n, name, header, fields
        self.rooms = []

    def room(self, *a, **o):
        r = Room(*a, **o); self.rooms.append(r)
        return r

    def write(self, path):
        lines = []
        if self.header:
            lines += ['// ' + l for l in self.header.strip().split('\n')]
        lines.append('// Generated by tools/' + os.path.basename(sys.argv[0]) + ' (builder C): edit that script and re-run.')
        lines.append('export default {')
        lines.append(f'  id: {json.dumps(self.id)}, n: {json.dumps(self.n)}, name: {json.dumps(self.name)},')
        for k, v in self.fields.items():
            lines.append(f'  {k}: {json.dumps(v)},')
        lines.append('  rooms: [')
        for r in self.rooms:
            lines.append(r.to_js())
        lines.append('  ],')
        lines.append('};')
        open(path, 'w').write('\n'.join(lines) + '\n')
        print('wrote', path, len(self.rooms), 'rooms')

    def dump(self, only=None):
        for r in self.rooms:
            if not only or r.id in only:
                r.dump()
