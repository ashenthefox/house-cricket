#!/usr/bin/env node
// Scans game/assets and writes game/data/assets.js: the list of asset files that exist.
// The sprite registry only requests files on this list, so a missing sprite falls back to
// shapes without a 404 in the console. Re-run after adding or removing assets:
//   node tools/list-assets.mjs
import { readdirSync, statSync, writeFileSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
const root = path.join(path.dirname(fileURLToPath(import.meta.url)), '..', 'game', 'assets');
const out = [];
(function walk(d) {
  let names = [];
  try { names = readdirSync(d); } catch { return; }
  for (const n of names.sort()) {
    if (n.startsWith('.')) continue;
    const p = path.join(d, n);
    if (statSync(p).isDirectory()) walk(p);
    else if (/\.(png|webp|jpe?g|json|mp3|ogg|m4a)$/i.test(n)) out.push(path.relative(root, p).split(path.sep).join('/'));
  }
})(root);
const file = path.join(root, '..', 'data', 'assets.js');
writeFileSync(file, `// Generated by tools/list-assets.mjs: every file under game/assets/. Do not edit by hand.\nexport const ASSET_FILES = ${JSON.stringify(out, null, 0).replace(/","/g, '",\n  "')};\n`);
console.log(`list-assets: ${out.length} files -> ${path.relative(process.cwd(), file)}`);
